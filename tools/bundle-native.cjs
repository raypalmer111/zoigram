'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../InzoiSocial/lua');

// Compile project-local modules into one ordinary Lua chunk. The game startup
// validator accepts engine modules only in require(), unlike its hot-reload path.
// All factories are literal code; there is no runtime file access or eval.
function buildNative({modId}={}){
 const modules=new Map();
 function collect(name){
  if(modules.has(name))return;
  if(name==='B1.UI.IconData'){const bytes=fs.readFileSync(path.resolve(root,'../assets/instagram-icon.png'));modules.set(name,'return {'+[...bytes].join(',')+'}\n');return;}
  if(!/^B1\.[A-Za-z0-9_.]+$/.test(name))throw Error('Unsupported module '+name);
  let file=path.join(root,name.replaceAll('.','/')+'.lua');
  if(!fs.existsSync(file)&&name.startsWith('B1.Shared.'))file=path.join(root,name.slice(3).replaceAll('.','/')+'.lua');
  let code=fs.readFileSync(file,'utf8').replace(/^\uFEFF/,'');modules.set(name,'');
  code=code.replace(/\brequire\(\s*'([^']+)'\s*\)/g,(_,dependency)=>{collect(dependency);return "zmodule('"+dependency+"')"});
  if(/\brequire\b/.test(code))throw Error('Unresolved module import in '+name);
  modules.set(name,code);
 }
 collect('B1.PhoneIntegration');
 let bundle=`-- Generated by tools/bundle-native.cjs; edit the modular source instead.
local factories, modules, loading = {}, {}, {}
local function zmodule(name)
 if modules[name]~=nil then return modules[name] end
 assert(not loading[name], 'Cyclic Zoigram module: '..name)
 local factory=assert(factories[name], 'Missing Zoigram module: '..name)
 loading[name]=true;local value=factory();loading[name]=nil
 assert(value~=nil, 'Empty Zoigram module: '..name);modules[name]=value;return value
end
`;
 for(const [name,code]of [...modules].sort(([a],[b])=>a.localeCompare(b)))bundle+="\n-- Source: "+name+"\nfactories['"+name+"']=function()\n"+code+"\nend\n";
 bundle+="\nreturn zmodule('B1.PhoneIntegration')\n";
 if(modId)bundle=bundle.replaceAll('__MOD_ID__',modId);
 const simulation=fs.readFileSync(path.join(root,'B2/CreatorPower.lua'),'utf8').replace(/^\uFEFF/,'');
 if(/\b(?:require|loadfile|loadstring|dofile)\s*\(/.test(simulation))throw Error('B2 CreatorPower must be self-contained');
 const files=[{path:'B1/PhoneIntegration.lua',content:bundle},{path:'B1/Main.lua',content:'-- The bound phone entry owns startup and cleanup.\nreturn {}\n'},{path:'B2/Main.lua',content:'return {}\n'},{path:'B2/CreatorPower.lua',content:simulation},{path:'lua_manifest.json',content:fs.readFileSync(path.join(root,'lua_manifest.json'),'utf8')}];
 return {files,modules:[...modules.keys()].sort()};
}
module.exports={buildNative};
